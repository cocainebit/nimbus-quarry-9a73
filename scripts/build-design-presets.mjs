// Offline conversion of pinned, licensed upstream theme data into safe app tokens.
// Run: node scripts/build-design-presets.mjs (requires Playwright Chromium).
import { readFile, writeFile } from "node:fs/promises";
import ts from "typescript";
import { chromium } from "@playwright/test";
import daisy from "../vendor/daisyui/themes.mjs";
import { mixColors, contrastRatio } from "../shared/design-colors.mjs";
const source = await readFile(
  new URL("../vendor/tweakcn/theme-presets.ts", import.meta.url),
  "utf8",
);
const javascript = ts.transpileModule(source, {
  compilerOptions: {
    module: ts.ModuleKind.ESNext,
    target: ts.ScriptTarget.ES2022,
  },
}).outputText;
const { defaultPresets: tweakcn } = await import(
  "data:text/javascript;base64," + Buffer.from(javascript).toString("base64")
);
const title = (s) =>
  s.replace(/(^|[-_ ])\w/g, (c) => c.replace(/[-_]/g, " ").toUpperCase());
const font = (value = "") =>
  /jetbrains|mono|menlo/i.test(value)
    ? "jetbrains"
    : /playfair|serif/i.test(value) && !/sans/i.test(value)
      ? "playfair"
      : /manrope|jakarta|poppins/i.test(value)
        ? "manrope"
        : /dm sans/i.test(value)
          ? "dm-sans"
          : "inter";
const radius = (value = "0.5rem") =>
  Math.max(
    0,
    Math.min(24, parseFloat(value) * (value.includes("rem") ? 16 : 1)),
  );
const presets = [];
for (const [key, entry] of Object.entries(tweakcn)) {
  for (const mode of ["light", "dark"]) {
    const s = { ...entry.styles.light, ...entry.styles[mode] };
    presets.push({
      id: `tweakcn-${key}-${mode}`,
      family: `tweakcn-${key}`,
      name: entry.label || title(key),
      description: `${mode === "dark" ? "Dark" : "Light"} · tweakcn`,
      source: "tweakcn",
      sourceUrl: "https://github.com/jnsahaj/tweakcn",
      mode,
      palette: {
        primary: s.primary,
        background: s.background,
        surface: s.card || s.background,
        text: s.foreground,
        muted: s["muted-foreground"],
        border: s.border,
      },
      font: font(s["font-sans"]),
      headingFont: font(s["font-sans"]),
      radius: radius(s.radius),
      density: "comfortable",
      navigation: "sidebar",
    });
  }
}
for (const [key, s] of Object.entries(daisy)) {
  const mode = s["color-scheme"] === "dark" ? "dark" : "light";
  presets.push({
    id: `daisyui-${key}`,
    family: `daisyui-${key}`,
    name: title(key),
    description: `${title(mode)} · daisyUI`,
    source: "daisyUI",
    sourceUrl: "https://daisyui.com/docs/themes/",
    mode,
    palette: {
      primary: s["--color-primary"],
      background: s["--color-base-200"],
      surface: s["--color-base-100"],
      text: s["--color-base-content"],
      muted: s["--color-base-content"],
      border: s["--color-base-300"],
    },
    font: "inter",
    radius: radius(s["--radius-box"]),
    density: "comfortable",
    navigation: "sidebar",
  });
}
const browser = await chromium.launch({ headless: true });
try {
  const page = await browser.newPage();
  for (const p of presets) {
    p.palette = await page.evaluate((palette) => {
      const canvas = document.createElement("canvas");
      canvas.width = canvas.height = 1;
      const ctx = canvas.getContext("2d", { willReadFrequently: true });
      return Object.fromEntries(
        Object.entries(palette).map(([key, value]) => {
          if (typeof value !== "string" || !CSS.supports("color", value))
            throw Error(`Unsupported ${key}: ${value}`);
          ctx.clearRect(0, 0, 1, 1);
          ctx.fillStyle = value;
          ctx.fillRect(0, 0, 1, 1);
          const bytes = ctx.getImageData(0, 0, 1, 1).data;
          if (bytes[3] !== 255) throw Error("Transparent theme token");
          return [
            key,
            "#" +
              Array.from(bytes)
                .slice(0, 3)
                .map((n) => n.toString(16).padStart(2, "0"))
                .join(""),
          ];
        }),
      );
    }, p.palette);
    // Adapt secondary text for the renderer's shared surfaces, preserving hue.
    const { surface, background, text } = p.palette;
    let muted =
      p.source === "daisyUI" ? mixColors(surface, text, 0.72) : p.palette.muted;
    for (
      let i = 0;
      i < 20 &&
      Math.min(
        contrastRatio(muted, surface),
        contrastRatio(muted, background),
      ) < 4.5;
      i++
    )
      muted = mixColors(muted, text, 0.2);
    p.palette.muted = muted;
  }
} finally {
  await browser.close();
}
presets.sort(
  (a, b) =>
    a.source.localeCompare(b.source) ||
    a.name.localeCompare(b.name) ||
    b.mode.localeCompare(a.mode),
);
await writeFile(
  new URL("../shared/design-presets.generated.mjs", import.meta.url),
  "// Generated by scripts/build-design-presets.mjs. Sources/licenses: vendor/README.md.\nexport const thirdPartyPresets = " +
    JSON.stringify(presets, null, 2) +
    ";\n",
);
console.log(
  `${new Set(presets.map((p) => p.family)).size} upstream theme families, ${presets.length} theme variants.`,
);
